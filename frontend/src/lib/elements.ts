/** Element symbol from a QE species label (Fe1, Fe_up, O2-). */
export function labelToElement(label: string): string {
  const m = label.trim().match(/^([A-Za-z]{1,2})/);
  if (!m) return 'X';
  const l = m[1];
  const pair = l[0].toUpperCase() + (l[1] ?? '').toLowerCase();
  const single = l[0].toUpperCase();
  if (l.length === 2 && (l[1] === l[1].toLowerCase() || l === l.toUpperCase()) && Z[pair] !== undefined) return pair;
  if (Z[single] !== undefined && single !== 'X') return single;
  if (Z[pair] !== undefined) return pair;
  return 'X';
}

